package Module3;

public class String_builder_Programe {

	public static void main(String[] args)
	{

     StringBuilder s=new StringBuilder("Automation");
       System.out.println(s.append(" Testing")); //Append
      
       System.out.println(s.insert(6, " API"));//insert
     
       System.out.println(s.delete(5, 9));//delete
     
       System.out.println(s.substring(6));//Substring
     
       System.out.println(s.capacity()); //capacity
       
       System.out.println(s.reverse());// reverse
    
     
     
     
      

	}

}
